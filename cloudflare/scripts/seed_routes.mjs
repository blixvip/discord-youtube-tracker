// Builds the D1 seed that hands creator routing to this Worker.
//
// Every route's checkpoint is refreshed from the creator's live Atom feed, so
// taking over the feed never replays a backlog of old uploads.
//
//   DISCORD_TOKEN=... node scripts/seed_routes.mjs > scripts/seed_routes.sql
//
// Apply with:
//   wrangler d1 execute discord-youtube-transcripts --remote --file scripts/seed_routes.sql

import { readFile } from "node:fs/promises";

const token = process.env.DISCORD_TOKEN;
if (!token) throw new Error("Set DISCORD_TOKEN before building the route seed.");

// Discord snowflakes exceed the safe integer range, so they are quoted before
// parsing instead of being silently rounded.
const raw = (await readFile(new URL("../../subscriptions.json", import.meta.url), "utf8"))
  .replace(/"discord_channel_id"\s*:\s*(\d+)/g, '"discord_channel_id": "$1"');
const source = JSON.parse(raw);
const routes = source.subscriptions ?? [];
if (!routes.length) throw new Error("subscriptions.json contains no routes.");

const quote = (value) => (value === null || value === undefined ? "NULL" : `'${String(value).replaceAll("'", "''")}'`);

async function latestVideoId(channelId) {
  const response = await fetch(`https://www.youtube.com/feeds/videos.xml?channel_id=${encodeURIComponent(channelId)}`);
  if (!response.ok) throw new Error(`feed ${channelId} returned ${response.status}`);
  return (await response.text()).match(/<yt:videoId>([A-Za-z0-9_-]{11})<\/yt:videoId>/)?.[1] ?? null;
}

async function guildFor(discordChannelId) {
  const response = await fetch(`https://discord.com/api/v10/channels/${discordChannelId}`, {
    headers: { authorization: `Bot ${token}` },
  });
  if (!response.ok) throw new Error(`channel ${discordChannelId} returned ${response.status}`);
  return (await response.json()).guild_id ?? null;
}

async function resolve(values, worker, size = 5) {
  const resolved = new Map();
  for (let index = 0; index < values.length; index += size) {
    await Promise.all(values.slice(index, index + size).map(async (value) => {
      try {
        resolved.set(value, await worker(value));
      } catch (error) {
        console.error(`-- skipped ${value}: ${error.message}`);
        resolved.set(value, null);
      }
    }));
  }
  return resolved;
}

const creators = [...new Set(routes.map((route) => route.youtube_channel_id))];
const channels = [...new Set(routes.map((route) => String(route.discord_channel_id)))];
const [checkpoints, guilds] = await Promise.all([
  resolve(creators, latestVideoId),
  resolve(channels, guildFor),
]);

const now = new Date().toISOString();
const lines = [
  "-- Generated by scripts/seed_routes.mjs. Checkpoints are the newest live upload,",
  "-- so this Worker starts watching forward instead of replaying history.",
];
let written = 0;
for (const route of routes) {
  const discordChannelId = String(route.discord_channel_id);
  const checkpoint = checkpoints.get(route.youtube_channel_id) ?? route.last_video_id;
  const guildId = guilds.get(discordChannelId);
  if (!guildId) continue;
  lines.push(
    "INSERT INTO routes (youtube_channel_id, youtube_channel_name, discord_channel_id, last_video_id, guild_id, enabled, added_at)",
    `VALUES (${quote(route.youtube_channel_id)}, ${quote(route.youtube_channel_name)}, ${quote(discordChannelId)}, ${quote(checkpoint)}, ${quote(guildId)}, 1, ${quote(now)})`,
    "ON CONFLICT(youtube_channel_id, discord_channel_id) DO UPDATE SET",
    "  youtube_channel_name = excluded.youtube_channel_name,",
    "  last_video_id = COALESCE(routes.last_video_id, excluded.last_video_id),",
    "  guild_id = excluded.guild_id,",
    "  enabled = 1;",
  );
  written += 1;
}
console.error(`-- ${written} route(s) ready, ${routes.length - written} skipped`);
console.log(lines.join("\n"));
