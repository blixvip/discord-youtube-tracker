import hashlib
import hmac
import json
import time
from typing import Optional

import aiohttp

from youtube_transcript import TranscriptBundle


def signed_caption_request(secret: str, timestamp: str, body: str) -> str:
    return hmac.new(
        secret.encode("utf-8"),
        f"{timestamp}.{body}".encode("utf-8"),
        hashlib.sha256,
    ).hexdigest()


class CaptionCacheClient:
    def __init__(self, url: str, secret: str):
        self.url = url
        self.secret = secret
        self._session: Optional[aiohttp.ClientSession] = None

    async def _get_session(self) -> aiohttp.ClientSession:
        if self._session is None or self._session.closed:
            self._session = aiohttp.ClientSession(timeout=aiohttp.ClientTimeout(total=4))
        return self._session

    async def store(self, bundle: TranscriptBundle) -> None:
        body = json.dumps({
            "videoId": bundle.video_id,
            "language": bundle.language,
            "plainText": bundle.plain_text,
            "srtText": bundle.srt_text,
            "title": bundle.title,
            "channelName": bundle.channel_name,
            "provider": bundle.provider,
            "sourceType": bundle.source_type,
            "isAutoGenerated": bundle.is_auto_generated,
        }, ensure_ascii=False, separators=(",", ":"))
        timestamp = str(int(time.time()))
        signature = signed_caption_request(self.secret, timestamp, body)
        session = await self._get_session()
        async with session.post(
            self.url,
            data=body.encode("utf-8"),
            headers={
                "content-type": "application/json",
                "x-caption-timestamp": timestamp,
                "x-caption-signature": signature,
            },
        ) as response:
            if not response.ok:
                detail = (await response.text())[:300]
                raise RuntimeError(f"Caption cache returned {response.status}: {detail}")

    async def exists(self, video_id: str) -> bool:
        timestamp = str(int(time.time()))
        signature = signed_caption_request(self.secret, timestamp, video_id)
        session = await self._get_session()
        async with session.head(
            f"{self.url.rstrip('/')}/{video_id}",
            headers={
                "x-caption-timestamp": timestamp,
                "x-caption-signature": signature,
            },
        ) as response:
            if response.status == 204:
                return True
            if response.status == 404:
                return False
            detail = (await response.text())[:300]
            raise RuntimeError(f"Caption cache status returned {response.status}: {detail}")

    async def close(self) -> None:
        if self._session and not self._session.closed:
            await self._session.close()
